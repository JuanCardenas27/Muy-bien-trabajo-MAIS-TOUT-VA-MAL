export type EsKey = keyof typeof es;

export function t(key: EsKey, vars?: Record<string, string | number>): string {
  let out: string = es[key];
  if (vars !== undefined) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replace(`{${name}}`, String(value));
    }
  }
  return out;
}
